import { existsSync } from "node:fs";
import type { NextConfig } from "next";
import { PHASE_DEVELOPMENT_SERVER } from "next/constants";

// Local development only: Next.js reads .env and .env.local by itself, so the mode
// file from D10 (.env.surface by default, or the one named by ENV_FILE) is loaded
// here. Never during `next build`: keys must not reach the build or the Docker image,
// and APP_MODE must stay a runtime choice (D10). In Docker, compose passes the variables.
function loadDevEnvFile() {
  const explicit = process.env.ENV_FILE;
  const file = explicit ?? ".env.surface";
  if (existsSync(file)) {
    process.loadEnvFile(file);
  } else if (explicit) {
    throw new Error(`ENV_FILE points to a missing file: ${explicit}`);
  }
}

export default function config(phase: string): NextConfig {
  if (phase === PHASE_DEVELOPMENT_SERVER) loadDevEnvFile();
  return {
    // Minimal self-contained server in .next/standalone, used by the Docker image (ARCHITECTURE.md, section 6).
    output: "standalone",
    // Tailwind CSS 4 is compiled by its Turbopack loader (generated by create-next-app);
    // the project builds with Turbopack only (D15).
    turbopack: {
      rules: {
        "*.css": {
          loaders: ["@tailwindcss/turbopack"],
          as: "*.css",
        },
      },
    },
  };
}
